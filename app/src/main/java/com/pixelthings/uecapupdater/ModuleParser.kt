package com.pixelthings.uecapupdater

import android.content.Context
import android.net.Uri
import com.topjohnwu.superuser.Shell
import java.io.BufferedInputStream
import java.io.File
import java.util.zip.ZipInputStream

object ModuleParser {

    /**
     * 掃描 Zip 模組包，找出裡面所有隱藏在 system/vendor/... 底下的 .binarypb
     */
    fun parseZipModule(context: Context, zipUri: Uri): List<PbFileInfo> {
        val fileList = mutableListOf<PbFileInfo>()
        runCatching {
            context.contentResolver.openInputStream(zipUri)?.use { inputStream ->
                ZipInputStream(BufferedInputStream(inputStream)).use { zis ->
                    var entry = zis.nextEntry
                    while (entry != null) {
                        // 只要檔名結尾是 .binarypb
                        if (!entry.isDirectory && entry.name.endsWith(".binarypb", ignoreCase = true)) {
                            val file = File(entry.name)
                            fileList.add(
                                PbFileInfo(
                                    fileName = file.name,
                                    insidePath = entry.name,
                                    zipUri = zipUri,
                                    entryName = entry.name
                                )
                            )
                        }
                        entry = zis.nextEntry
                    }
                }
            }
        }.onFailure { it.printStackTrace() }
        return fileList
    }

    /**
     * 🚀 終極開機魔法：動態生成真正的 Magisk 模組
     * 交給 Magisk 原生的 Magic Mount 引擎處理開機全域掛載，100% 絕對生效！
     */
    fun createMagiskModule(isEn: Boolean): Boolean {
        val moduleDir = "/data/adb/modules/uecapupdater_live"
        val vendorDir = "$moduleDir/system/vendor/firmware/uecapconfig"
        val otaDir = "/data/vendor/radio/ota_uecap"
        val d = "$"

        val moduleName = if (isEn) "UECapUpdater Auto-Mount" else "UECapUpdater 自動掛載模組"
        val moduleDesc = if (isEn) {
            "Baseband config module dynamically generated by the App to ensure persistence after reboot. Click 'Restore Factory' in the App to remove."
        } else {
            "由 App 動態生成的基帶配置模組，確保重開機後不掉檔。若要清除請在 App 內點擊「恢復原廠」。"
        }

        val command = """
            set -e
            mkdir -p "$vendorDir"
            
            # 自動撰寫 Magisk 模組設定檔
            cat << 'EOF' > "$moduleDir/module.prop"
            id=uecapupdater_live
            name=$moduleName
            version=v1.0
            versionCode=1
            author=UECapUpdater App
            description=$moduleDesc
            EOF
            
            # 清空舊模組檔案
            rm -f "$vendorDir"/*.binarypb
            
            # 將目前 App 匯入的配置複製到 Magisk 模組結構中
            if [ -d "$otaDir" ]; then
                for FILE in "$otaDir"/*.binarypb; do
                    if [ -f "${d}FILE" ]; then
                        cp "${d}FILE" "$vendorDir/"
                    fi
                done
            fi
            
            # 設定標準的模組權限
            chmod -R 755 "$moduleDir"
            chmod 644 "$moduleDir/module.prop"
            chmod 644 "$vendorDir"/*.binarypb 2>/dev/null
            
        """.trimIndent()

        // Keep fail-fast settings inside a child shell; libsu's main shell is reused.
        return Shell.cmd("sh -c ${shellQuote(command)}").exec().isSuccess
    }

    /**
     * 刪除 Magisk 掛載模組 (恢復原廠時使用)
     */
    fun removeMagiskModule() {
        Shell.cmd("rm -rf /data/adb/modules/uecapupdater_live").exec()
    }
}
